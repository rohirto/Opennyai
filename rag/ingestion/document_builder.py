"""
Canonical legal document builder for the OpenNyAI-based RAG pipeline.

Pipeline
--------
OpenNyAI outputs
    |
    +-- Rhetorical Role Classification (RRC)
    |
    +-- Named Entity Recognition (NER)
    |
    +-- Extractive Summarizer
    |
    v
LegalDocument
    |
    v
rag.ingestion.chunker
    |
    v
LegalChunk


Important design principle
--------------------------
The cleaned legal judgment remains the authoritative source text.

NER and summarizer outputs are enrichment/context layers.

RRC provides the legal rhetorical structure.

This module does NOT:
    - generate embeddings
    - communicate with Qdrant
    - call the LLM
    - perform retrieval
    - perform semantic chunking
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional
import hashlib
import json


# ============================================================================
# Configuration
# ============================================================================

DOCUMENT_SCHEMA_VERSION = "2.0"

DEFAULT_LANGUAGE = "en"
DEFAULT_SOURCE_TYPE = "legal_judgment"


# ============================================================================
# Data models
# ============================================================================

@dataclass
class LegalAnnotation:
    """
    One OpenNyAI rhetorical-role annotation.

    RRC annotations are treated as the fundamental legal structural units.
    """

    annotation_id: str

    text: str

    role: str

    char_start: int
    char_end: int

    annotation_index: int


@dataclass
class LegalEntity:
    """
    Normalized NER entity.

    Offsets are optional because different OpenNyAI NER output formats may
    provide or omit them.
    """

    entity_id: str

    text: str

    label: str

    char_start: Optional[int] = None
    char_end: Optional[int] = None
    
    normalized_name: str | None = None

    source: str = "opennyai_ner"


@dataclass
class LegalSummary:
    """
    Document-level summary generated by the OpenNyAI summarizer.

    These are NOT authoritative legal source text. They are contextual
    information used to enrich retrieval and generation.
    """

    preamble: Optional[str] = None
    facts: Optional[str] = None
    issue: Optional[str] = None
    arguments: Optional[str] = None
    analysis: Optional[str] = None
    decision: Optional[str] = None

    # Preserve any additional sections emitted by a future OpenNyAI
    # summarizer version.
    extra: Dict[str, str] = field(default_factory=dict)


@dataclass
class LegalDocument:
    """
    Canonical legal document representation.

    This is the contract between document_builder.py and chunker.py.
    """

    document_id: str

    source_file: Optional[str]

    source_type: str

    language: str

    text: str

    text_length: int

    annotations: List[LegalAnnotation]

    annotation_count: int

    entities: List[LegalEntity]

    entity_count: int

    summary: LegalSummary

    # Optional trusted document metadata.
    case_name: Optional[str] = None
    citation: Optional[str] = None
    court: Optional[str] = None
    judgment_date: Optional[str] = None

    schema_version: str = DOCUMENT_SCHEMA_VERSION


# ============================================================================
# Generic JSON helpers
# ============================================================================

def load_json(path: str | Path) -> Any:
    """
    Load UTF-8 JSON from disk.
    """

    path = Path(path)

    with path.open(
        "r",
        encoding="utf-8",
    ) as file:
        return json.load(file)


def save_json(
    data: Any,
    path: str | Path,
    *,
    indent: int = 2,
) -> None:
    """
    Save UTF-8 JSON.
    """

    path = Path(path)

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with path.open(
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            data,
            file,
            ensure_ascii=False,
            indent=indent,
        )


# ============================================================================
# Document ID
# ============================================================================

def generate_document_id(
    source_text: str,
) -> str:
    """
    Generate deterministic SHA-256 document ID.

    This is only used if OpenNyAI did not provide an ID.
    """

    return hashlib.sha256(
        source_text.encode("utf-8")
    ).hexdigest()


# ============================================================================
# RRC normalization
# ============================================================================

def get_role(
    annotation: Dict[str, Any],
) -> str:
    """
    Extract the rhetorical role from an OpenNyAI annotation.

    Expected form:

        "labels": ["ANALYSIS"]

    If no label exists, UNKNOWN is used.
    """

    labels = annotation.get("labels") or []

    if isinstance(labels, str):
        return labels.strip() or "UNKNOWN"

    if not labels:
        return "UNKNOWN"

    return str(
        labels[0]
    ).strip() or "UNKNOWN"


def get_annotation_text(
    annotation: Dict[str, Any],
    source_text: str,
) -> str:
    """
    Obtain annotation text.

    Prefer the text explicitly emitted by OpenNyAI.
    Otherwise reconstruct it from source offsets.
    """

    if annotation.get("text") is not None:
        return str(
            annotation["text"]
        )

    start = int(
        annotation["start"]
    )

    end = int(
        annotation["end"]
    )

    return source_text[start:end]


def normalize_annotations(
    source_text: str,
    annotations: Iterable[Dict[str, Any]],
) -> List[LegalAnnotation]:
    """
    Normalize raw OpenNyAI RRC annotations.

    Original character offsets are preserved.
    """

    normalized: List[LegalAnnotation] = []

    previous_end = -1

    for index, annotation in enumerate(annotations):

        if "start" not in annotation:
            raise ValueError(
                f"RRC annotation {index} is missing 'start'."
            )

        if "end" not in annotation:
            raise ValueError(
                f"RRC annotation {index} is missing 'end'."
            )

        start = int(
            annotation["start"]
        )

        end = int(
            annotation["end"]
        )

        if start < 0:
            raise ValueError(
                f"RRC annotation {index} has negative start."
            )

        if end < start:
            raise ValueError(
                f"RRC annotation {index} has end < start."
            )

        if end > len(source_text):
            raise ValueError(
                f"RRC annotation {index} ends at {end}, "
                f"but source length is {len(source_text)}."
            )

        if start < previous_end:
            raise ValueError(
                "Overlapping RRC annotations detected: "
                f"annotation {index} starts at {start}, "
                f"previous annotation ended at {previous_end}."
            )

        normalized.append(
            LegalAnnotation(
                annotation_id=str(
                    annotation.get(
                        "id",
                        f"annotation_{index}",
                    )
                ),
                text=get_annotation_text(
                    annotation,
                    source_text,
                ),
                role=get_role(
                    annotation
                ),
                char_start=start,
                char_end=end,
                annotation_index=index,
            )
        )

        previous_end = end

    return normalized


