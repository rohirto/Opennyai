def document_to_dict(
    document: LegalDocument,
) -> Dict[str, Any]:
    """
    Convert LegalDocument into JSON-compatible dictionary.
    """

    return asdict(
        document
    )


def save_document(
    document: LegalDocument,
    path: str | Path,
) -> None:
    """
    Save a LegalDocument to JSON.
    """

    save_json(
        document_to_dict(
            document
        ),
        path,
    )


# ============================================================================
# Validation
# ============================================================================

def validate_document(
    document: LegalDocument,
) -> None:
    """
    Validate the canonical document.

    RRC offsets must:
        - be non-negative
        - be ordered
        - not overlap
        - stay within source text
    """

    if not document.document_id:
        raise ValueError(
            "Document has no document_id."
        )

    if not document.text:
        raise ValueError(
            "Document has empty text."
        )

    if document.text_length != len(
        document.text
    ):
        raise ValueError(
            "Document text_length does not match "
            "actual text length."
        )

    if document.annotation_count != len(
        document.annotations
    ):
        raise ValueError(
            "Document annotation_count does not match "
            "actual annotation count."
        )

    if document.entity_count != len(
        document.entities
    ):
        raise ValueError(
            "Document entity_count does not match "
            "actual entity count."
        )

    previous_end = -1

    for annotation in document.annotations:

        if annotation.char_start < 0:
            raise ValueError(
                f"Negative annotation start: "
                f"{annotation.annotation_id}"
            )

        if annotation.char_end < annotation.char_start:
            raise ValueError(
                f"Invalid annotation offsets: "
                f"{annotation.annotation_id}"
            )

        if annotation.char_end > document.text_length:
            raise ValueError(
                f"Annotation extends beyond document: "
                f"{annotation.annotation_id}"
            )

        if annotation.char_start < previous_end:
            raise ValueError(
                f"Overlapping annotation: "
                f"{annotation.annotation_id}"
            )

        previous_end = annotation.char_end

    for entity in document.entities:

        if entity.char_start is None:
            continue

        if entity.char_start < 0:
            raise ValueError(
                f"Invalid entity start: "
                f"{entity.entity_id}"
            )

        if (
            entity.char_end is not None
            and entity.char_end < entity.char_start
        ):
            raise ValueError(
                f"Invalid entity offsets: "
                f"{entity.entity_id}"
            )

        if (
            entity.char_end is not None
            and entity.char_end > document.text_length
        ):
            raise ValueError(
                f"Entity extends beyond document: "
                f"{entity.entity_id}"
            )


# ============================================================================
# Statistics
# ============================================================================

def document_statistics(
    document: LegalDocument,
) -> Dict[str, Any]:
    """
    Generate useful M1 diagnostics.
    """

    role_counts: Dict[str, int] = {}

    for annotation in document.annotations:

        role = annotation.role

        role_counts[role] = (
            role_counts.get(
                role,
                0
            ) + 1
        )

    entity_counts: Dict[str, int] = {}

    for entity in document.entities:

        label = entity.label

        entity_counts[label] = (
            entity_counts.get(
                label,
                0
            ) + 1
        )

    return {
        "document_id": document.document_id,

        "source_file": document.source_file,

        "text_length": document.text_length,

        "annotation_count": document.annotation_count,

        "entity_count": document.entity_count,

        "rhetorical_roles": role_counts,

        "entity_types": entity_counts,

        "summary_sections": [
            key
            for key, value
            in asdict(
                document.summary
            ).items()
            if value
        ],

        "case_name": document.case_name,

        "citation": document.citation,

        "court": document.court,
    }


